use camino::Utf8Path;

use crate::DayModule;
use crate::examples::Example;

const HEADER: &str = "// Generated by elfcode-build from the day files in src/. Do not edit.\n";

/// Renders the module declarations, the example tests and the registry for
/// `days`, which must be ordered by year.
///
/// Written out as text rather than built with `quote`: the output is small
/// and regular, and this crate is compiled in every user's build.
pub(crate) fn render(crate_root: &Utf8Path, days: &[DayModule]) -> String {
    let modules = days
        .chunk_by(|a, b| a.puzzle.year() == b.puzzle.year())
        .map(|year_days| year_module(crate_root, year_days))
        .collect::<Vec<_>>()
        .concat();

    let entries = days
        .iter()
        .map(|DayModule { puzzle, .. }| {
            let (year, day) = (puzzle.year(), puzzle.day());
            format!("::elfcode::__private::Entry::of::<y{year}::day{day:02}::Day{day:02}>({year}, {day}),\n")
        })
        .collect::<Vec<_>>()
        .concat();

    format!(
        "{HEADER}\n{modules}static REGISTRY: &[::elfcode::__private::Entry] = &[\n{}];\n",
        indent(&entries)
    )
}

fn year_module(crate_root: &Utf8Path, days: &[DayModule]) -> String {
    let year = days[0].puzzle.year();
    let items = days
        .iter()
        .map(|day| day_items(crate_root, day))
        .collect::<Vec<_>>()
        .concat();

    format!("pub mod y{year} {{\n{}}}\n\n", indent(&items))
}

fn day_items(crate_root: &Utf8Path, day: &DayModule) -> String {
    let number = day.puzzle.day();
    // Absolute, because a relative `#[path]` would resolve against the
    // generated file's directory instead of the crate's.
    let path = crate_root.join(&day.path);
    let declaration = format!("#[path = {:?}]\npub mod day{number:02};\n", path.as_str());

    if day.examples.is_empty() {
        return declaration;
    }

    let examples = day
        .examples
        .iter()
        .zip(1..)
        .map(|(example, number)| example_module(number, example))
        .collect::<Vec<_>>()
        .join("\n");
    let body = format!("use super::day{number:02}::Day{number:02} as Day;\n\n{examples}");

    format!(
        "{declaration}#[cfg(test)]\nmod day{number:02}_examples {{\n{}}}\n",
        indent(&body)
    )
}

fn example_module(number: usize, example: &Example) -> String {
    let tests = example
        .answers
        .iter()
        .map(|(part, expected)| {
            // `{part:?}` is the variant name, `One` or `Two`.
            format!(
                "#[test]\nfn part{part}() {{\n    ::elfcode::__private::assert_example::<super::Day>(\n        ::elfcode::__private::Part::{part:?},\n        INPUT,\n        {expected:?},\n    );\n}}\n"
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let body = format!("const INPUT: &str = {:?};\n\n{tests}", example.input);

    format!("mod example_{number} {{\n{}}}\n", indent(&body))
}

/// Indents by one level. Safe on generated code because every string
/// literal in it is escaped onto a single line.
fn indent(text: &str) -> String {
    text.lines()
        .map(|line| {
            if line.is_empty() {
                "\n".to_owned()
            } else {
                format!("    {line}\n")
            }
        })
        .collect::<Vec<_>>()
        .concat()
}

#[cfg(test)]
mod tests {
    use elfcode_core::{Day, Part, PuzzleId, Year};

    use super::*;

    fn day(year: u16, day: u8, examples: Vec<Example>) -> DayModule {
        DayModule {
            puzzle: PuzzleId::new(Year::new(year).unwrap(), Day::new(day).unwrap()).unwrap(),
            path: format!("src/y{year}/day{day:02}.rs").into(),
            examples,
        }
    }

    fn example(input: &str, answers: &[(Part, &str)]) -> Example {
        Example {
            input: input.to_owned(),
            answers: answers
                .iter()
                .map(|&(part, answer)| (part, answer.to_owned()))
                .collect(),
        }
    }

    #[test]
    fn renders_one_module_per_year_and_one_entry_per_day() {
        let days = [
            day(2025, 12, Vec::new()),
            day(2026, 1, Vec::new()),
            day(2026, 3, Vec::new()),
        ];

        let rendered = render(Utf8Path::new("/work/solutions"), &days);

        assert_eq!(
            rendered,
            r#"// Generated by elfcode-build from the day files in src/. Do not edit.

pub mod y2025 {
    #[path = "/work/solutions/src/y2025/day12.rs"]
    pub mod day12;
}

pub mod y2026 {
    #[path = "/work/solutions/src/y2026/day01.rs"]
    pub mod day01;
    #[path = "/work/solutions/src/y2026/day03.rs"]
    pub mod day03;
}

static REGISTRY: &[::elfcode::__private::Entry] = &[
    ::elfcode::__private::Entry::of::<y2025::day12::Day12>(2025, 12),
    ::elfcode::__private::Entry::of::<y2026::day01::Day01>(2026, 1),
    ::elfcode::__private::Entry::of::<y2026::day03::Day03>(2026, 3),
];
"#
        );
    }

    #[test]
    fn renders_one_test_per_example_per_part() {
        let examples = vec![
            example("1 2\n  3\n", &[(Part::One, "11"), (Part::Two, "31")]),
            example("say \"hi\"", &[(Part::Two, "hi")]),
        ];

        let rendered = render(Utf8Path::new("/work"), &[day(2026, 3, examples)]);

        assert_eq!(
            rendered,
            r#"// Generated by elfcode-build from the day files in src/. Do not edit.

pub mod y2026 {
    #[path = "/work/src/y2026/day03.rs"]
    pub mod day03;
    #[cfg(test)]
    mod day03_examples {
        use super::day03::Day03 as Day;

        mod example_1 {
            const INPUT: &str = "1 2\n  3\n";

            #[test]
            fn part1() {
                ::elfcode::__private::assert_example::<super::Day>(
                    ::elfcode::__private::Part::One,
                    INPUT,
                    "11",
                );
            }

            #[test]
            fn part2() {
                ::elfcode::__private::assert_example::<super::Day>(
                    ::elfcode::__private::Part::Two,
                    INPUT,
                    "31",
                );
            }
        }

        mod example_2 {
            const INPUT: &str = "say \"hi\"";

            #[test]
            fn part2() {
                ::elfcode::__private::assert_example::<super::Day>(
                    ::elfcode::__private::Part::Two,
                    INPUT,
                    "hi",
                );
            }
        }
    }
}

static REGISTRY: &[::elfcode::__private::Entry] = &[
    ::elfcode::__private::Entry::of::<y2026::day03::Day03>(2026, 3),
];
"#
        );
    }

    #[test]
    fn renders_an_empty_registry_for_a_crate_without_days() {
        let rendered = render(Utf8Path::new("/work/solutions"), &[]);

        assert_eq!(
            rendered,
            "// Generated by elfcode-build from the day files in src/. Do not edit.\n\n\
             static REGISTRY: &[::elfcode::__private::Entry] = &[\n];\n"
        );
    }

    #[test]
    fn escapes_a_windows_path() {
        let rendered = render(Utf8Path::new(r"C:\work"), &[day(2026, 1, Vec::new())]);

        assert!(rendered.contains(r#"#[path = "C:\\work"#), "{rendered}");
    }
}
