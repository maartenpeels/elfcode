use camino::Utf8Path;

use crate::discover::DayFile;

const HEADER: &str = "// Generated by elfcode-build from the day files in src/. Do not edit.\n";

/// Renders the module declarations and the registry for `days`, which must
/// be ordered by year.
///
/// Written out as text rather than built with `quote`: the output is small
/// and regular, and this crate is compiled in every user's build.
pub(crate) fn render(crate_root: &Utf8Path, days: &[DayFile]) -> String {
    let modules = days
        .chunk_by(|a, b| a.puzzle.year() == b.puzzle.year())
        .map(|year_days| year_module(crate_root, year_days))
        .collect::<Vec<_>>()
        .concat();

    let entries = days
        .iter()
        .map(|DayFile { puzzle, .. }| {
            let (year, day) = (puzzle.year(), puzzle.day());
            format!(
                "    ::elfcode::Entry::of::<y{year}::day{day:02}::Day{day:02}>({year}, {day}),\n"
            )
        })
        .collect::<Vec<_>>()
        .concat();

    format!("{HEADER}\n{modules}static REGISTRY: &[::elfcode::Entry] = &[\n{entries}];\n")
}

fn year_module(crate_root: &Utf8Path, days: &[DayFile]) -> String {
    let year = days[0].puzzle.year();
    let declarations = days
        .iter()
        .map(|DayFile { puzzle, path }| {
            // Absolute, because a relative `#[path]` would resolve against
            // the generated file's directory instead of the crate's.
            let path = crate_root.join(path);
            format!(
                "    #[path = {:?}]\n    pub mod day{:02};\n",
                path.as_str(),
                puzzle.day()
            )
        })
        .collect::<Vec<_>>()
        .concat();

    format!("pub mod y{year} {{\n{declarations}}}\n\n")
}

#[cfg(test)]
mod tests {
    use elfcode_core::{Day, PuzzleId, Year};

    use super::*;

    fn day_file(year: u16, day: u8) -> DayFile {
        DayFile {
            puzzle: PuzzleId::new(Year::new(year).unwrap(), Day::new(day).unwrap()).unwrap(),
            path: format!("src/y{year}/day{day:02}.rs").into(),
        }
    }

    #[test]
    fn renders_one_module_per_year_and_one_entry_per_day() {
        let days = [day_file(2025, 12), day_file(2026, 1), day_file(2026, 3)];

        let rendered = render(Utf8Path::new("/work/solutions"), &days);

        assert_eq!(
            rendered,
            r#"// Generated by elfcode-build from the day files in src/. Do not edit.

pub mod y2025 {
    #[path = "/work/solutions/src/y2025/day12.rs"]
    pub mod day12;
}

pub mod y2026 {
    #[path = "/work/solutions/src/y2026/day01.rs"]
    pub mod day01;
    #[path = "/work/solutions/src/y2026/day03.rs"]
    pub mod day03;
}

static REGISTRY: &[::elfcode::Entry] = &[
    ::elfcode::Entry::of::<y2025::day12::Day12>(2025, 12),
    ::elfcode::Entry::of::<y2026::day01::Day01>(2026, 1),
    ::elfcode::Entry::of::<y2026::day03::Day03>(2026, 3),
];
"#
        );
    }

    #[test]
    fn renders_an_empty_registry_for_a_crate_without_days() {
        let rendered = render(Utf8Path::new("/work/solutions"), &[]);

        assert_eq!(
            rendered,
            "// Generated by elfcode-build from the day files in src/. Do not edit.\n\n\
             static REGISTRY: &[::elfcode::Entry] = &[\n];\n"
        );
    }

    #[test]
    fn escapes_a_windows_path() {
        let rendered = render(Utf8Path::new(r"C:\work"), &[day_file(2026, 1)]);

        assert!(rendered.contains(r#"#[path = "C:\\work"#), "{rendered}");
    }
}
